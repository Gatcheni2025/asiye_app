"use strict";

// Generate a staging-only Cloud Functions entrypoint, without modifying
// committed production source. Firebase discovers exported endpoints even when
// --only functions:<name> is used, so omitted wallet/Twilio-backed exports
// must not become part of the isolated Paystack staging trigger manifest.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const manifest = require("./paystack_function_manifest.json");
const {requireStagingConfig} = require("./build_staging_web_preview.cjs");

const NAME_RE = /^[A-Za-z][A-Za-z0-9]*$/;
function verifyNames(names) {
  if (!Array.isArray(names) || names.length === 0) throw Error("Function allowlist is empty");
  if (new Set(names).size !== names.length) throw Error("Function allowlist has duplicate names");
  if (names.some(n => typeof n !== "string" || !NAME_RE.test(n))) {
    throw Error("Function allowlist has an invalid function name");
  }
  const legacy = ["createEftSmsTopup", "initializePaystackWalletTopup", "verifyPaystackWalletTopup",
    "sendEftPaymentStatusSms", "notifyDriversWhenClubReady"];
  if (names.some(n => legacy.includes(n))) throw Error("A legacy wallet/Twilio function is in the staging allowlist");
}
function renderEntry(names) {
  verifyNames(names);
  // Embed ONLY public function identifiers, no user data or credentials. The
  // wrapper's exports determine what Firebase's discovery code sees.
  return [
    '"use strict";',
    "// AUTOGENERATED in the isolated GitHub staging job; do not commit.",
    'const all = require("./index.js");',
    "const required = " + JSON.stringify(names) + ";",
    "for (const name of required) {",
    '  if (typeof all[name] !== "function") throw Error("Missing reviewed staging function export: " + name);',
    "}",
    "module.exports = Object.fromEntries(required.map(name => [name, all[name]]));",
    ""
  ].join("\n");
}
function main() {
  if (process.env.STAGING_PROJECT !== "asiye-paystack-staging" ||
      process.env.GITHUB_REF_NAME !== "fix/paystack-subaccounts-cash-card-no-wallet") {
    throw Error("Function scope preparation is restricted to the isolated staging workflow");
  }
  // A bare Node require() has no Firebase CLI-generated FIREBASE_CONFIG.
  // Explicitly verify that its database URL is the isolated staging RTDB.
  let stagingConfig;
  try {
    stagingConfig = JSON.parse(process.env.FIREBASE_CONFIG || "{}");
  } catch (_) {
    throw Error("Missing or invalid staging Firebase runtime configuration");
  }
  requireStagingConfig(stagingConfig, process.env.STAGING_PROJECT);
  verifyNames(manifest);
  const pkgFile = path.join(root, "functions", "package.json");
  const pkg = JSON.parse(fs.readFileSync(pkgFile, "utf8"));
  if (pkg.main !== "index.js") throw Error("Refusing to replace an unexpected Functions entrypoint");
  const entryFile = path.join(root, "functions", "staging-index.generated.cjs");
  if (fs.existsSync(entryFile)) throw Error("Staging entrypoint already exists");
  fs.writeFileSync(entryFile, renderEntry(manifest), {flag:"wx", mode:0o644});
  pkg.main = "staging-index.generated.cjs";
  fs.writeFileSync(pkgFile, JSON.stringify(pkg,null,2)+"\n");
  console.log("Isolated staging Functions entrypoint restricted to " + manifest.length + " reviewed exports.");
  console.log("Legacy wallet and Twilio-only exports are not part of Firebase staging discovery.");
}
if (require.main === module) main();
module.exports = {renderEntry, verifyNames};
